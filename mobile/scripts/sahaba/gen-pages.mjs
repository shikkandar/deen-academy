#!/usr/bin/env node
// Hayatus Sahaba arrives page by page (scripts/sahaba/RULES.md): this lists whatever pages are in assets/sahaba now
// and writes src/lib/sahaba-pages.ts (native: required when opened) and its web twin (fetched from /data when opened).
// Rerun after new pages land:   node scripts/sahaba/gen-pages.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const ASSETS = path.join(ROOT, 'assets/sahaba');
const LANGS = ['ta', 'ar', 'en', 'tp'];

const ids = {};
for (const lang of LANGS) {
  const dir = path.join(ASSETS, lang);
  ids[lang] = fs.existsSync(dir)
    ? fs
        .readdirSync(dir)
        .filter((f) => /^\d{4}\.json$/.test(f))
        .filter((f) => {
          try {
            return Array.isArray(JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).blocks);
          } catch {
            console.warn('skipping broken page', lang, f);
            return false;
          }
        })
        .map((f) => Number(f.slice(0, 4)))
        .sort((a, b) => a - b)
    : [];
}

const head = (what) =>
  `// Generated by scripts/sahaba/gen-pages.mjs — do not edit by hand.\n// ${what}\n\n`;
const lists = LANGS.map((l) => `  ${l}: [${ids[l].join(', ')}],`).join('\n');

let native = head('Each page is required only when it is opened.') + 'type Loader = () => unknown;\n\n';
native += `export const PAGE_IDS: Record<'ta' | 'ar' | 'en' | 'tp', number[]> = {\n${lists}\n};\n\n`;
native += `export const PAGES: Record<'ta' | 'ar' | 'en' | 'tp', Record<number, Loader>> = {\n`;
for (const l of LANGS) {
  native += `  ${l}: {\n`;
  for (const id of ids[l]) native += `    ${id}: () => require('@/assets/sahaba/${l}/${String(id).padStart(4, '0')}.json'),\n`;
  native += '  },\n';
}
// The apps load pages the same way as the web (downloaded once, then kept on the phone), so nothing is bundled.
void native;
fs.writeFileSync(
  path.join(ROOT, 'src/lib/sahaba-pages.ts'),
  "// Generated by scripts/sahaba/gen-pages.mjs — the apps load pages the same way as the web (see sahaba-pages.web.ts).\nexport * from './sahaba-pages.web';\n",
);

let web = head('Each page fetched from /data when opened (src/lib/remote-data.ts; the apps keep a copy on the phone).');
web += `import { getData as get } from './remote-data';\n\ntype Loader = () => Promise<unknown>;\n\n`;
web += `export const PAGE_IDS: Record<'ta' | 'ar' | 'en' | 'tp', number[]> = {\n${lists}\n};\n\n`;
web += `export const PAGES: Record<'ta' | 'ar' | 'en' | 'tp', Record<number, Loader>> = {\n`;
for (const l of LANGS) {
  web += `  ${l}: {\n`;
  for (const id of ids[l]) web += `    ${id}: () => get('/data/sahaba/${l}/${String(id).padStart(4, '0')}.json'),\n`;
  web += '  },\n';
}
fs.writeFileSync(path.join(ROOT, 'src/lib/sahaba-pages.web.ts'), web + '};\n');
console.log('sahaba pages', Object.fromEntries(LANGS.map((l) => [l, ids[l].length])));

// Web search: one compact file per language, [[page id, block, text], …], fetched only when Hayatus Sahaba is searched
// (the native apps search the bundled pages directly). Generated, not committed (.gitignore).
for (const lang of LANGS) {
  const rows = [];
  for (const id of ids[lang]) {
    const page = JSON.parse(fs.readFileSync(path.join(ASSETS, lang, `${String(id).padStart(4, '0')}.json`), 'utf8'));
    page.blocks.forEach((b, i) => {
      for (const k of ['text', 'arabic_text', 'narrator', 'source']) if (b[k] && b[k].trim()) rows.push([id, i, b[k]]);
    });
  }
  fs.writeFileSync(path.join(ASSETS, `search-${lang}.json`), JSON.stringify(rows));
}
console.log('sahaba search files written');
