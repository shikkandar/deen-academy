#!/usr/bin/env node
// Bundles a hadith book into the app, like Muntakhab: one JSON per chapter in assets/hadith/<book>/<chapter>.json
// (Arabic + English from fawazahmed0/hadith-api, plus our own Tamil translation), then regenerates
// src/lib/hadith-bundled.ts so each chapter is required only when it is opened.
//
//   node scripts/bundle-hadith.mjs <book> [tamil.json]
//
// tamil.json maps hadith number -> Tamil text, e.g. {"1": "...", "2": "..."}. It can cover only part of the book:
// Tamil already bundled for other hadith is kept, so a book can be translated a few chapters at a time.

import fs from 'node:fs';
import path from 'node:path';

const API = 'https://raw.githubusercontent.com/fawazahmed0/hadith-api/1/editions'; // jsDelivr 403s uncached files
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'assets/hadith');
const NARRATOR = /^Narrated ([^:]{1,80}):\s*/; // same as src/lib/hadith-books.ts

const [book, tamilFile] = process.argv.slice(2);
if (!book) {
  console.error('usage: node scripts/bundle-hadith.mjs <book> [tamil.json]');
  process.exit(1);
}
const index = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets/data/hadith-books.json'), 'utf8'));
const info = index.books.find((b) => b.id === book);
if (!info) throw new Error(`unknown book ${book}`);
const tamil = tamilFile ? JSON.parse(fs.readFileSync(tamilFile, 'utf8')) : {};

async function section(edition, id) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(`${API}/${edition}/sections/${id}.min.json`);
    if (res.ok) return res.json();
    if (attempt === 3) throw new Error(`${edition} ${id}: HTTP ${res.status}`);
    await new Promise((r) => setTimeout(r, 2000 * attempt));
  }
}

fs.mkdirSync(path.join(OUT, book), { recursive: true });
let withTamil = 0;
let total = 0;
for (const s of info.sections) {
  const file = path.join(OUT, book, `${s.id}.json`);
  const old = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : [];
  const oldTamil = new Map(old.map((h) => [h.number, h.tamil]));
  const [eng, ara] = await Promise.all([section(`eng-${book}`, s.id), section(`ara-${book}`, s.id)]);
  const arabicByNumber = new Map(ara.hadiths.map((h) => [h.hadithnumber, h.text]));
  const hadiths = eng.hadiths
    .filter((h) => h.text.trim())
    .map((h) => {
      const text = h.text.replace(/\s+/g, ' ').trim();
      const m = text.match(NARRATOR);
      const g = h.grades?.[0];
      const ta = (tamil[h.hadithnumber] ?? oldTamil.get(h.hadithnumber) ?? '').trim();
      return {
        number: h.hadithnumber,
        arabic: (arabicByNumber.get(h.hadithnumber) ?? '').trim(),
        english: m ? text.slice(m[0].length) : text,
        tamil: ta || null,
        narrator: m ? m[1] : null,
        grade: g ? `${g.grade} (${g.name})` : null,
      };
    });
  total += hadiths.length;
  withTamil += hadiths.filter((h) => h.tamil).length;
  fs.writeFileSync(file, JSON.stringify(hadiths));
}
console.log(`${book}: ${info.sections.length} chapters, ${total} hadith, ${withTamil} with Tamil`);

// Regenerate the loader for every bundled book.
const books = fs.readdirSync(OUT).filter((d) => fs.statSync(path.join(OUT, d)).isDirectory()).sort();
const lines = [
  '// Generated by scripts/bundle-hadith.mjs — do not edit by hand.',
  '// Hadith books bundled in the app (Arabic, English and our Tamil). Each chapter is required only when it is opened.',
  '',
  'type Loader = () => unknown;',
  '',
  'export const BUNDLED: Record<string, Record<number, Loader>> = {',
];
for (const b of books) {
  const ids = fs
    .readdirSync(path.join(OUT, b))
    .filter((f) => f.endsWith('.json'))
    .map((f) => Number(f.slice(0, -5)))
    .sort((x, y) => x - y);
  lines.push(`  ${b}: {`);
  for (const id of ids) lines.push(`    ${id}: () => require('@/assets/hadith/${b}/${id}.json'),`);
  lines.push('  },');
}
lines.push('};', '');
fs.writeFileSync(path.join(ROOT, 'src/lib/hadith-bundled.ts'), lines.join('\n'));
