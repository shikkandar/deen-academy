#!/usr/bin/env node
// Word times of the recitations whose timings we made by forced alignment against the text the app shows: the
// spoken translations (English Ibrahim Walk, Tamil Omar Sharif, Urdu Shamshad Ali Khan; per word of the shown
// translation) and Arabic reciters that Quran.com has no timings for (Maher al-Muaiqly, Abdullah Basfar; per
// Quran.com word). One JSON per surah in assets/wordtimes/<dir>. Writes the loaders: native bundles each surah's
// file (required when opened), web fetches it from /data/wordtimes (public/data links to assets/).
//   node scripts/gen-word-times.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
// Audio edition → folder in assets/wordtimes.
const EDITIONS = {
  'en.walk': 'en',
  'ta.omar': 'ta',
  'ur.khan': 'ur',
  'ar.mahermuaiqly': 'maher',
  'ar.abdullahbasfar': 'basfar',
};
const head = (how) =>
  `// Generated by scripts/gen-word-times.mjs — do not edit by hand.\n// Word times per audio edition and surah: ${how}.\n\n`;
let native = head('bundled, required when the surah is opened') + 'export const WORD_TIMES: Record<string, Record<number, () => unknown>> = {\n';
let web =
  head('fetched from /data when the surah is opened (src/lib/remote-data.ts; the apps keep a copy on the phone)') +
  "import { getData as get } from './remote-data';\n\n" +
  'export const WORD_TIMES: Record<string, Record<number, () => unknown>> = {\n';
for (const [edition, dir] of Object.entries(EDITIONS)) {
  const full = path.join(ROOT, 'assets/wordtimes', dir);
  if (!fs.existsSync(full)) continue;
  const surahs = fs
    .readdirSync(full)
    .filter((f) => /^\d+\.json$/.test(f))
    .map((f) => Number(f.slice(0, -5)))
    .sort((a, b) => a - b);
  native += `  '${edition}': {\n`;
  web += `  '${edition}': {\n`;
  for (const n of surahs) {
    native += `    ${n}: () => require('@/assets/wordtimes/${dir}/${n}.json'),\n`;
    web += `    ${n}: () => get('/data/wordtimes/${dir}/${n}.json'),\n`;
  }
  native += '  },\n';
  web += '  },\n';
  console.log(edition, surahs.length, 'surahs');
}
// The apps load them the same way as the web (downloaded once, then kept on the phone), so nothing is bundled.
void native;
fs.writeFileSync(
  path.join(ROOT, 'src/lib/word-times.ts'),
  "// Generated by scripts/gen-word-times.mjs — the apps load word times the same way as the web (see word-times.web.ts).\nexport * from './word-times.web';\n",
);
fs.writeFileSync(path.join(ROOT, 'src/lib/word-times.web.ts'), web + '};\n');
