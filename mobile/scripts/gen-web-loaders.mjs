#!/usr/bin/env node
// ~60 MB of hadith and 1,824 Muntakhab pages are too much to bundle, so every chapter / page is fetched from /data/...
// when it is opened: on web from the site itself (public/data links to assets/), in the apps from the web app on
// Netlify and then kept on the phone (src/lib/remote-data.ts). This writes src/lib/hadith-bundled.web.ts and
// muntakhab-pages.web.ts from the files in assets/, and the native .ts files that re-export them.
//   node scripts/gen-web-loaders.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const lib = (f) => path.join(ROOT, 'src/lib', f);
const head = (what) =>
  `// Generated by scripts/gen-web-loaders.mjs — do not edit by hand.\n// ${what} fetched from /data when opened (src/lib/remote-data.ts; the apps keep a copy on the phone).\n\n` +
  `import { getData as get } from './remote-data';\n\ntype Loader = () => Promise<unknown>;\n\n`;
const reexport = (name) =>
  fs.writeFileSync(lib(`${name}.ts`), `// Generated by scripts/gen-web-loaders.mjs — the apps load the books the same way as the web (see ${name}.web.ts).\nexport * from './${name}.web';\n`);
const jsonIds = (dir) =>
  fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort((a, b) => Number(a) - Number(b));
const ASSETS = path.join(ROOT, 'assets');

// hadith
const books = {};
for (const b of fs.readdirSync(path.join(ASSETS, 'hadith')).sort())
  if (fs.statSync(path.join(ASSETS, 'hadith', b)).isDirectory()) books[b] = jsonIds(path.join(ASSETS, 'hadith', b)).map(Number);
let out = head('each hadith chapter') + 'export const BUNDLED: Record<string, Record<number, Loader>> = {\n';
for (const [b, ids] of Object.entries(books)) {
  out += `  ${b}: {\n`;
  for (const id of ids) out += `    ${id}: () => get('/data/hadith/${b}/${id}.json'),\n`;
  out += '  },\n';
}
fs.writeFileSync(lib('hadith-bundled.web.ts'), out + '};\n');
reexport('hadith-bundled');

// muntakhab
const munt = { ta: jsonIds(path.join(ASSETS, 'muntakhab/ta')), en: jsonIds(path.join(ASSETS, 'muntakhab/en')) };
const numbers = `export const PAGE_NUMBERS = [${[...new Set([...munt.ta, ...munt.en].map(Number))].sort((a, b) => a - b).join(', ')}];`;
let m = head('each Muntakhab page') + numbers + '\n\nexport const PAGES: Record<\'ta\' | \'en\', Record<number, Loader>> = {\n';
for (const lang of ['ta', 'en']) {
  m += `  ${lang}: {\n`;
  for (const x of munt[lang]) m += `    ${Number(x)}: () => get('/data/muntakhab/${lang}/${x}.json'),\n`;
  m += '  },\n';
}
fs.writeFileSync(lib('muntakhab-pages.web.ts'), m + '};\n');
reexport('muntakhab-pages');
console.log('books', Object.keys(books).length, 'chapters', Object.values(books).flat().length);
