#!/usr/bin/env node
// Web builds can't bundle ~60 MB of hadith and 1,824 Muntakhab pages into the JS, so on web each chapter / page is
// fetched from /data/... when it is opened (served from public/data, which links to assets/). This writes the
// .web.ts twins of src/lib/hadith-bundled.ts and src/lib/muntakhab-pages.ts with the same keys.
//   node scripts/gen-web-loaders.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const lib = (f) => path.join(ROOT, 'src/lib', f);
const head = (what) =>
  `// Generated by scripts/gen-web-loaders.mjs — do not edit by hand.\n// Web: ${what} fetched from /data when opened (native bundles them; see the .ts twin).\n\n` +
  `type Loader = () => Promise<unknown>;\n\nconst get = (url: string): Promise<unknown> => fetch(url).then((r) => (r.ok ? r.json() : null));\n\n`;

// hadith
const hadith = fs.readFileSync(lib('hadith-bundled.ts'), 'utf8');
const books = {};
for (const m of hadith.matchAll(/require\('@\/assets\/hadith\/([a-z0-9]+)\/(\d+)\.json'\)/g)) (books[m[1]] ??= []).push(Number(m[2]));
let out = head('each hadith chapter') + 'export const BUNDLED: Record<string, Record<number, Loader>> = {\n';
for (const [b, ids] of Object.entries(books)) {
  out += `  ${b}: {\n`;
  for (const id of ids) out += `    ${id}: () => get('/data/hadith/${b}/${id}.json'),\n`;
  out += '  },\n';
}
fs.writeFileSync(lib('hadith-bundled.web.ts'), out + '};\n');

// muntakhab
const pages = fs.readFileSync(lib('muntakhab-pages.ts'), 'utf8');
const numbers = pages.match(/export const PAGE_NUMBERS = \[[^\]]*\];/)[0];
let m = head('each Muntakhab page') + numbers + '\n\nexport const PAGES: Record<\'ta\' | \'en\', Record<number, Loader>> = {\n';
for (const lang of ['ta', 'en']) {
  m += `  ${lang}: {\n`;
  for (const x of pages.matchAll(new RegExp(`require\\('@/assets/muntakhab/${lang}/(\\d+)\\.json'\\)`, 'g')))
    m += `    ${Number(x[1])}: () => get('/data/muntakhab/${lang}/${x[1]}.json'),\n`;
  m += '  },\n';
}
fs.writeFileSync(lib('muntakhab-pages.web.ts'), m + '};\n');
console.log('books', Object.keys(books).length, 'chapters', Object.values(books).flat().length);
